DROP DATABASE IF EXISTS astronomija;

CREATE DATABASE astronomija
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE astronomija;

DROP TABLE IF EXISTS Opservacija;
DROP TABLE IF EXISTS Vremenski_Uslovi;
DROP TABLE IF EXISTS Sesija;
DROP TABLE IF EXISTS Izvodjac_Eksperimenta;
DROP TABLE IF EXISTS Izvodjenje;
DROP TABLE IF EXISTS Dizajner_Eksperimenta;
DROP TABLE IF EXISTS Alat;
DROP TABLE IF EXISTS Nebeski_Objekat;
DROP TABLE IF EXISTS Eksperiment;
DROP TABLE IF EXISTS Tip_Alata;
DROP TABLE IF EXISTS Resurs;
DROP TABLE IF EXISTS Laboratorija;
DROP TABLE IF EXISTS Teorija;
DROP TABLE IF EXISTS Istrazivac;

CREATE TABLE Istrazivac (
  ID_Istrazivaca  INT PRIMARY KEY AUTO_INCREMENT,
  Naziv           VARCHAR(100) NOT NULL,
  Kvalifikacija   VARCHAR(100),
  Email           VARCHAR(100) UNIQUE
);

CREATE TABLE Teorija (
  ID_Teorije  INT PRIMARY KEY AUTO_INCREMENT,
  Naziv       VARCHAR(100) NOT NULL,
  Opis        TEXT
);

CREATE TABLE Laboratorija (
  ID_Lab                INT PRIMARY KEY AUTO_INCREMENT,
  Naziv                 VARCHAR(100) NOT NULL,
  Opis_Lokacije         TEXT,
  Geografske_Koordinate VARCHAR(50),
  Nadmorska_Visina      DECIMAL(8,2),
  Tip                   ENUM('Opticka_Opservatorija',
                              'Radio_Opservatorija',
                              'Svemirska_Opservatorija',
                              'Podzemna_Istrazivacka_Stanica')
);

CREATE TABLE Resurs (
  ID_Resursa    INT PRIMARY KEY AUTO_INCREMENT,
  Naziv         VARCHAR(100) NOT NULL,
  Tip           ENUM('Detektorski_Materijal',
                     'Skup_Podataka_Kalibracija',
                     'Izvor_Energije',
                     'Nebeski_Objekat',
					 'Termin_Posmatranja'),
  Dodatni_Opis  TEXT,
  Datum_Nabavke DATE,
  Dostupnost    ENUM('dostupan','u_upotrebi','nedostupan')
);

CREATE TABLE Tip_Alata (
  ID_Tipa  INT PRIMARY KEY AUTO_INCREMENT,
  Naziv    VARCHAR(100) NOT NULL,
  Opis     TEXT
);

CREATE TABLE Eksperiment (
  ID_Eksperimenta  INT PRIMARY KEY AUTO_INCREMENT,
  ID_Teorije       INT,
  Naziv            VARCHAR(100) NOT NULL,
  Tip              ENUM('Opticka_Teleskopska_Opservacija',
                        'Radio_Astronomski_Eksperiment',
                        'Detekcija_Kozmickog_Zraca'),
  FOREIGN KEY (ID_Teorije) REFERENCES Teorija(ID_Teorije)
);

CREATE TABLE Nebeski_Objekat (
  ID_Nebeskog_Objekta  INT PRIMARY KEY AUTO_INCREMENT,
  ID_Resursa           INT UNIQUE,
  Naucni_Naziv         VARCHAR(100),
  Tip_Objekta          ENUM('Zvezda','Galaksija','Maglina',
                             'Pulsar','Crna_Rupa','Egzoplaneta'),
  Velicina             DECIMAL(15,4),
  Lokacija_u_Svemiru   VARCHAR(100),
  Udaljenost_od_Zemlje DECIMAL(15,4),
  FOREIGN KEY (ID_Resursa) REFERENCES Resurs(ID_Resursa)
);

CREATE TABLE Alat (
  ID_Alata          INT PRIMARY KEY AUTO_INCREMENT,
  ID_Lab            INT NOT NULL,
  ID_Tipa           INT,
  Naziv 			Varchar(100),
  Datum_Nabavke     DATE,
  Datum_Proizvodnje DATE,
  FOREIGN KEY (ID_Lab)  REFERENCES Laboratorija(ID_Lab),
  FOREIGN KEY (ID_Tipa) REFERENCES Tip_Alata(ID_Tipa)
);

CREATE TABLE Dizajner_Eksperimenta (
  ID_Dizajnera    INT PRIMARY KEY AUTO_INCREMENT,
  ID_Istrazivaca  INT,
  Uloga_Dizajnera VARCHAR(100),
  FOREIGN KEY (ID_Istrazivaca) REFERENCES Istrazivac(ID_Istrazivaca)
);

CREATE TABLE Izvodjenje (
  ID_Izvodjenja   INT PRIMARY KEY AUTO_INCREMENT,
  ID_Eksperimenta INT NOT NULL,
  ID_Lab          INT NOT NULL,
  Datum           DATE,
  Status          ENUM('planirano','zapoceto','otkazano',
                       'zavrseno_uspesno','zavrseno_neuspesno'),
  FOREIGN KEY (ID_Eksperimenta) REFERENCES Eksperiment(ID_Eksperimenta),
  FOREIGN KEY (ID_Lab)          REFERENCES Laboratorija(ID_Lab)
);

CREATE TABLE Izvodjac_Eksperimenta (
  ID_Istrazivaca  INT,
  ID_Izvodjenja   INT,
  Opis_Uloge      VARCHAR(100),
  Evidencija      VARCHAR(255),
  Sati_Rada       DECIMAL(6,2),
  Doprinos        TEXT,
  PRIMARY KEY (ID_Istrazivaca, ID_Izvodjenja),
  FOREIGN KEY (ID_Istrazivaca) REFERENCES Istrazivac(ID_Istrazivaca),
  FOREIGN KEY (ID_Izvodjenja)  REFERENCES Izvodjenje(ID_Izvodjenja)
);

CREATE TABLE Sesija (
  ID_Sesije       INT PRIMARY KEY AUTO_INCREMENT,
  ID_Izvodjenja   INT NOT NULL,
  ID_Lab          INT NOT NULL,
  Datum           DATE,
  Vreme_Pocetka   TIME,
  Vreme_Zavrsetka TIME,
  Tip_Sesije      ENUM('nocna','dnevna'),
  FOREIGN KEY (ID_Izvodjenja) REFERENCES Izvodjenje(ID_Izvodjenja),
  FOREIGN KEY (ID_Lab)        REFERENCES Laboratorija(ID_Lab)
);

CREATE TABLE Vremenski_Uslovi (
  ID_Vremenskih_Uslova  INT PRIMARY KEY AUTO_INCREMENT,
  ID_Sesije             INT UNIQUE NOT NULL,
  Temperatura           DECIMAL(5,2),
  Vlaznost              INT,
  Pritisak              DECIMAL(7,2),
  Vidljivost            DECIMAL(5,2),
  Oblacnost             ENUM('vedro','delimicno_oblacno','oblacno'),
  FOREIGN KEY (ID_Sesije) REFERENCES Sesija(ID_Sesije)
);

CREATE TABLE Opservacija (
  ID_Opservacije     INT PRIMARY KEY AUTO_INCREMENT,
  ID_Sesije          INT NOT NULL,
  Broj_Ekspozicija   INT,
  Izmerena_Magnituda DECIMAL(6,3),
  SNR                DECIMAL(8,3),
  Kvalitet_Podataka  ENUM('odlican','dobar','slab','neupotrebljiv'),
  Napomena           TEXT,
  FOREIGN KEY (ID_Sesije) REFERENCES Sesija(ID_Sesije)
);

CREATE TABLE t_o_Objektu (
    ID_Teorije          INT,
    ID_Nebeskog_Objekta INT,
    Opis_Veze           TEXT,
    PRIMARY KEY (ID_Teorije, ID_Nebeskog_Objekta),
    FOREIGN KEY (ID_Teorije)          REFERENCES Teorija(ID_Teorije),
    FOREIGN KEY (ID_Nebeskog_Objekta) REFERENCES Nebeski_Objekat(ID_Nebeskog_Objekta)
);

CREATE TABLE Op_O_Objektu (
    ID_Opservacije      INT,
    ID_Nebeskog_Objekta INT,
    Napomena            TEXT,
    PRIMARY KEY (ID_Opservacije, ID_Nebeskog_Objekta),
    FOREIGN KEY (ID_Opservacije)      REFERENCES Opservacija(ID_Opservacije),
    FOREIGN KEY (ID_Nebeskog_Objekta) REFERENCES Nebeski_Objekat(ID_Nebeskog_Objekta)
);

CREATE TABLE U_Labu (
    ID_Resursa  INT,
    ID_Lab      INT,
    Kolicina    DECIMAL(10,2),
    Jedinica    VARCHAR(20),
    Napomena    TEXT,
    PRIMARY KEY (ID_Resursa, ID_Lab),
    FOREIGN KEY (ID_Resursa) REFERENCES Resurs(ID_Resursa),
    FOREIGN KEY (ID_Lab)     REFERENCES Laboratorija(ID_Lab)
);

CREATE TABLE Koriscen_U_Eks (
    ID_Eksperimenta INT,
    ID_Alata        INT,
    PRIMARY KEY (ID_Eksperimenta, ID_Alata),
    FOREIGN KEY (ID_Eksperimenta) REFERENCES Eksperiment(ID_Eksperimenta),
    FOREIGN KEY (ID_Alata)        REFERENCES Alat(ID_Alata)
);

CREATE TABLE Dizajnirao_Eks (
    ID_Dizajnera    INT,
    ID_Eksperimenta INT,
    PRIMARY KEY (ID_Dizajnera, ID_Eksperimenta),
    FOREIGN KEY (ID_Dizajnera)    REFERENCES Dizajner_Eksperimenta(ID_Dizajnera),
    FOREIGN KEY (ID_Eksperimenta) REFERENCES Eksperiment(ID_Eksperimenta)
);

